"""Create a periodic, two-H-atom-per-H2 LAMMPS data file for teaching.

The generated geometry is deterministic for a fixed seed and contains only
hydrogen molecules. It does not select or validate an H2 force field.

Run from the lammps directory:
    python build_h2_data.py
    python build_h2_data.py --cells 3 --box-angstrom 26.0 --seed 7

For the supplied input script, keep the default 2 cells / 16 Å cubic box.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np

HYDROGEN_MASS_G_MOL = 1.008


def fcc_centers(cells: int, box_length: float) -> np.ndarray:
    """4*cells**3 lattice sites, in an orthorhombic cubic box [0,L)^3."""
    if cells < 1:
        raise ValueError("cells must be >= 1")
    if box_length <= 0:
        raise ValueError("box length must be positive")
    basis = np.array([[0, 0, 0], [.5, .5, 0], [.5, 0, .5], [0, .5, .5]], float)
    cellsize = box_length / cells
    centers = [
        (np.array([i, j, k]) + b) * cellsize
        for i in range(cells) for j in range(cells) for k in range(cells)
        for b in basis
    ]
    return np.array(centers, dtype=float)


def build_coordinates(cells: int = 2, box_length: float = 16.,
                      bond_length: float = .7414, seed: int = 2026) -> np.ndarray:
    """Return (molecules, 2, xyz); each bonded pair starts inside the box."""
    if cells < 1 or box_length <= 0:
        raise ValueError("cells must be >= 1 and box length positive")
    if bond_length <= 0 or bond_length >= box_length / (2 * cells):
        raise ValueError("bond length must be > 0 and less than half cell size")
    rng = np.random.default_rng(seed)
    centers = fcc_centers(cells, box_length)
    # Shift all COM sites by a quarter unit cell, to ensure all atoms start in box.
    centers = (centers + box_length / (4 * cells)) % box_length
    axes = rng.normal(size=centers.shape)
    axes /= np.linalg.norm(axes, axis=1)[:, None]
    coordinates = np.stack((centers - .5 * bond_length * axes,
                            centers + .5 * bond_length * axes), axis=1)
    if np.any(coordinates < 0) or np.any(coordinates >= box_length):
        raise RuntimeError("initial atom out of box; adjust placement")
    return coordinates


def write_lammps_data(path: str | Path, atoms: np.ndarray, box_length: float) -> Path:
    """Write one atom type, one bond type, molecule ID=1..N, atoms sorted."""
    atoms = np.asarray(atoms, dtype=float)
    if atoms.ndim != 3 or atoms.shape[1:] != (2, 3):
        raise ValueError("atoms must have shape (n_molecules, 2, 3)")
    if not np.isfinite(atoms).all() or np.any(atoms < 0) or np.any(atoms >= box_length):
        raise ValueError("atomic coordinates outside [0, box_length)")
    num_molecules = atoms.shape[0]
    if not num_molecules:
        raise ValueError("at least one molecule required")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "H2 diatomic teaching system, generated by build_h2_data.py",
        "",
        f"{2 * num_molecules} atoms",
        f"{num_molecules} bonds",
        "",
        "1 atom types",
        "1 bond types",
        "",
        f"0.0 {box_length:.8f} xlo xhi",
        f"0.0 {box_length:.8f} ylo yhi",
        f"0.0 {box_length:.8f} zlo zhi",
        "",
        "Masses",
        "",
        f"1 {HYDROGEN_MASS_G_MOL:.6f} # H atom, g/mol",
        "",
        "Atoms # molecular",
        "",
    ]
    for mol_index, pair in enumerate(atoms, start=1):
        for side, xyz in enumerate(pair):
            atom_id = 2 * (mol_index - 1) + side + 1
            lines.append(
                f"{atom_id} {mol_index} 1 " + " ".join(f"{x:.9f}" for x in xyz)
            )
    lines += ["", "Bonds", ""]
    for mol_index in range(1, num_molecules + 1):
        lines.append(f"{mol_index} 1 {2*mol_index-1} {2*mol_index}")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cells", type=int, default=2)
    parser.add_argument("--box-angstrom", type=float, default=16.)
    parser.add_argument("--bond-angstrom", type=float, default=.7414)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--output", default="h2_system.data")
    args = parser.parse_args(argv)
    coords = build_coordinates(args.cells, args.box_angstrom,
                               args.bond_angstrom, args.seed)
    out = write_lammps_data(args.output, coords, args.box_angstrom)
    print(f"Created {out.resolve()} | {len(coords)} H2 molecules / "
          f"{2*len(coords)} atoms | cubic box {args.box_angstrom:g} Å")
    print("Geometry only: simulation uses illustrative, NOT validated, H2 interactions.")


if __name__ == "__main__":
    main()
