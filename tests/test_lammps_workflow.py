"""Unit tests for the new H2/LAMMPS demo geometry and import contract.

These tests DO NOT run LAMMPS. Full engine integration must be tested with
an installed LAMMPS executable before claiming simulation success.
"""
from __future__ import annotations

import sys
from pathlib import Path
import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lammps"))
from build_h2_data import build_coordinates, fcc_centers, write_lammps_data
from h2md.atomistic import load_atomistic_lammps_dump


def test_geometry_has_two_explicit_h_atoms_per_molecule():
    coords = build_coordinates()
    assert coords.shape == (32, 2, 3)
    assert np.all((coords > 0) & (coords < 16))
    distances = np.linalg.norm(coords[:, 1] - coords[:, 0], axis=-1)
    np.testing.assert_allclose(distances, 0.7414, rtol=0, atol=1e-12)
    assert fcc_centers(2, 16).shape == (32, 3)


def test_data_file_sections_and_molecule_ids(tmp_path):
    path = write_lammps_data(tmp_path / "h2.data", build_coordinates(), 16)
    text = path.read_text()
    assert "64 atoms" in text and "32 bonds" in text
    assert "Atoms # molecular" in text
    assert "Bonds" in text
    atoms_section = text.split("Atoms # molecular\n\n", 1)[1].split("\n\nBonds", 1)[0]
    atom_lines = atoms_section.splitlines()
    assert len(atom_lines) == 64
    ids = [int(line.split()[0]) for line in atom_lines]
    mols = [int(line.split()[1]) for line in atom_lines]
    assert ids == list(range(1, 65))
    assert mols == [i for i in range(1, 33) for _ in range(2)]
    bond_section = text.split("\nBonds\n\n", 1)[1]
    bond_lines = bond_section.strip().splitlines()
    assert len(bond_lines) == 32
    assert bond_lines[0] == "1 1 1 2"
    assert bond_lines[-1] == "32 1 63 64"


def _synthetic_dump(coords, path, steps=(0, 100)):
    """Test-only dump; explicitly synthetic, not generated by LAMMPS."""
    with path.open("w", encoding="utf-8") as f:
        for t in steps:
            f.write("ITEM: TIMESTEP\n%d\n" % t)
            f.write("ITEM: NUMBER OF ATOMS\n%d\n" % (coords.shape[0]*2))
            f.write("ITEM: BOX BOUNDS pp pp pp\n0 16\n0 16\n0 16\n")
            f.write("ITEM: ATOMS id mol type xu yu zu\n")
            # Reverse order to assert parser tracks atom/molecule identity by ID.
            rows = []
            for mol_idx, pair in enumerate(coords):
                for atom_index, xyz in enumerate(pair):
                    atom_id = 2*mol_idx + atom_index + 1
                    displacement = np.array([17.0, -1.0, 0.5]) if t else np.zeros(3)
                    pos = xyz + displacement
                    rows.append((atom_id,mol_idx+1,1,*pos))
            for line in reversed(rows):
                f.write(f"{line[0]} {line[1]} {line[2]} " + " ".join(str(x) for x in line[3:]) + "\n")


def test_import_preserves_bond_and_unwrapped_com(tmp_path):
    coords=build_coordinates()
    dump = tmp_path / "h2_synthetic.lammpstrj"
    _synthetic_dump(coords, dump)
    traj = load_atomistic_lammps_dump(dump, timestep_fs=0.1)
    assert traj.atoms.shape == (2, 32, 2, 3)
    assert traj.frame_dt == pytest.approx(10.0)
    assert traj.length_unit == "angstrom"
    assert traj.time_unit == "fs"
    np.testing.assert_allclose(traj.atoms[0], coords, atol=1e-8)
    np.testing.assert_allclose(traj.com[1] - traj.com[0],
                               np.tile([17., -1., 0.5], (32, 1)), atol=1e-8)
    np.testing.assert_allclose(traj.bond_lengths(), .7414, atol=1e-8)


def test_reject_invalid_geometry(tmp_path):
    with pytest.raises(ValueError):
        build_coordinates(cells=0)
    with pytest.raises(ValueError):
        build_coordinates(bond_length=6.0)
    with pytest.raises(ValueError):
        write_lammps_data(tmp_path / "bad.data", np.zeros((3, 3, 3)), 16)
